-- SpotSync Person 1 canonical additive migration (PostgreSQL 17+).
-- Adds pending-booking expiry, parking sessions, and hashed ticket tokens.
-- Review on a restored disposable database before applying to any shared DB.
-- Does not delete/relabel existing slots, sensors, bookings, users, or IDs.

BEGIN;

ALTER TABLE public.bookings
    ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ NULL;

CREATE INDEX IF NOT EXISTS ix_bookings_pending_expiry
    ON public.bookings (expires_at)
    WHERE status = 'pending' AND expires_at IS NOT NULL;

-- A composite unique key lets the session FK guarantee that the slot belongs
-- to the stated lot. Existing primary keys and identifiers remain unchanged.
CREATE UNIQUE INDEX IF NOT EXISTS uq_parking_slots_lot_id_id
    ON public.parking_slots (parking_lot_id, id);

CREATE TABLE IF NOT EXISTS public.parking_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parking_lot_id BIGINT NOT NULL,
    parking_slot_id BIGINT NOT NULL,
    user_id BIGINT NULL,
    vehicle_id BIGINT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_parking_sessions_slot_in_lot
        FOREIGN KEY (parking_lot_id, parking_slot_id)
        REFERENCES public.parking_slots (parking_lot_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_sessions_user FOREIGN KEY (user_id)
        REFERENCES public.users(id) ON DELETE SET NULL,
    CONSTRAINT fk_parking_sessions_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES public.vehicles(id) ON DELETE SET NULL,
    CONSTRAINT ck_parking_sessions_status
        CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_parking_sessions_time_order
        CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT ck_active_session_has_no_end_time
        CHECK (status <> 'ACTIVE' OR ended_at IS NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_parking_sessions_one_active_per_slot
    ON public.parking_sessions (parking_slot_id) WHERE status = 'ACTIVE';
CREATE INDEX IF NOT EXISTS ix_parking_sessions_lot_started
    ON public.parking_sessions (parking_lot_id, started_at DESC);
CREATE INDEX IF NOT EXISTS ix_parking_sessions_user_started
    ON public.parking_sessions (user_id, started_at DESC) WHERE user_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_parking_sessions_updated_at ON public.parking_sessions;
CREATE TRIGGER update_parking_sessions_updated_at
    BEFORE UPDATE ON public.parking_sessions
    FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- Store SHA-256 hashes only. Raw QR bearer tokens must never be persisted.
CREATE TABLE IF NOT EXISTS public.ticket_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parking_session_id BIGINT NOT NULL
        REFERENCES public.parking_sessions(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NULL,
    used_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ticket_tokens_sha256_hex
        CHECK (token_hash ~ '^[0-9a-f]{64}$')
);
CREATE INDEX IF NOT EXISTS ix_ticket_tokens_session
    ON public.ticket_tokens (parking_session_id);
CREATE INDEX IF NOT EXISTS ix_ticket_tokens_expiry
    ON public.ticket_tokens (expires_at)
    WHERE revoked_at IS NULL AND used_at IS NULL;

COMMIT;
